/** Agent family grouping for Tool Thresholds UI. */
export function toolThresholdAgentGroup(toolName: string): string {
  const n = toolName.toLowerCase();
  if (toolName === '*' || n === 'bash' || n === 'execute_bash' || n === 'run_command' || n === 'shell') {
    return 'All Agents';
  }
  if (n === 'apply_patch') return 'Codex';
  if (
    n === 'run_terminal_cmd' ||
    n === 'write_file' ||
    n === 'search_replace' ||
    n === 'replace_file_content' ||
    n === 'view_file' ||
    n === 'grep_search' ||
    n === 'list_dir'
  ) {
    return 'Cursor / Antigravity';
  }
  return 'Claude Code';
}

