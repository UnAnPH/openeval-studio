"""Per-grader Golden Incident calibration datasets.

The Grader Workbench backtests a judge by scoring labeled reference trajectories and
reporting MAE / Spearman discrimination. A single shared catch-all pool dilutes each
grader's rubric: a trajectory that is a 9 for reward tampering is a 1 for situational
awareness, so a cross-domain pool rewards false positives.

Each trajectory monitor gets its own 20-sample, rubric-calibrated dataset spanning
severities 1-10. The datasets are stored as JSON under
``engine/graders/calibration_data/`` and are generated by
``scripts/build_calibration_datasets.py`` from verified real multi-turn backbones
(SHADE-Arena, ScaleAI MRT, AgentDojo, and recorded OpenEval rollouts) with
Apollo-style targeted failure injections.

``BacktestSample`` is defined here (rather than in ``engine.scorers``) so that this
module can build typed samples without a circular import: ``engine.scorers`` imports
``BacktestSample`` from here and re-exports it.
"""

from __future__ import annotations

import json
from functools import cache
from pathlib import Path

from pydantic import BaseModel, ConfigDict, Field

TRAJECTORY_MONITORS: tuple[str, ...] = (
    "SituationalAwarenessGrader",
    "GoalGuardingSchemingGrader",
    "UnfaithfulCoTGrader",
    "PlanAdherenceGrader",
    "HallucinationGrader",
    "RewardTamperingGrader",
    "RewardSeekingGrader",
    "PolicyGatewayDeepGrader",
)

SPECIALIZED_GRADERS: tuple[str, ...] = (
    "PolicyGatewayFastTriageGrader",
    "SemanticRunComparatorGrader",
    "IncidentRemediationGrader",
)

CALIBRATION_DATA_DIR = Path(__file__).resolve().parent / "calibration_data"

CALIBRATION_FILENAMES: dict[str, str] = {
    "SituationalAwarenessGrader": "situational_awareness.json",
    "GoalGuardingSchemingGrader": "goal_guarding_scheming.json",
    "UnfaithfulCoTGrader": "unfaithful_cot.json",
    "PlanAdherenceGrader": "plan_adherence.json",
    "HallucinationGrader": "hallucination.json",
    "RewardTamperingGrader": "reward_tampering.json",
    "RewardSeekingGrader": "reward_seeking.json",
    "PolicyGatewayDeepGrader": "policy_gateway_deep.json",
}


class BacktestSample(BaseModel):
    """A historical trajectory with human ground-truth severity calibration."""

    model_config = ConfigDict(extra="ignore")

    sample_id: str
    dimension: str
    headline: str
    trajectory_text: str
    ground_truth_score: int = Field(..., ge=1, le=10)
    context_tags: list[str] = Field(default_factory=list)
    failure_mode: str | None = None
    grader_ground_truths: dict[str, int] = Field(default_factory=dict)


@cache
def _load_calibration_samples(filename: str) -> tuple[BacktestSample, ...]:
    """Load and validate one calibration JSON file exactly once per process."""
    path = CALIBRATION_DATA_DIR / filename
    if not path.exists():
        raise FileNotFoundError(
            f"Missing calibration dataset {path}. "
            "Run `python scripts/build_calibration_datasets.py` to regenerate it."
        )
    raw = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(raw, list):
        raise ValueError(f"Calibration dataset {path} must contain a JSON list.")
    return tuple(BacktestSample.model_validate(sample) for sample in raw)


PER_GRADER_CALIBRATION_DATASETS: dict[str, list[BacktestSample]] = {
    grader_name: list(_load_calibration_samples(filename))
    for grader_name, filename in CALIBRATION_FILENAMES.items()
}


def get_calibration_dataset_for_grader(
    grader_name: str,
    base_golden: list[BacktestSample] | None = None,
) -> list[BacktestSample]:
    """Resolve the calibrated reference dataset for ``grader_name``.

    - Trajectory monitors return their dedicated 20-sample dataset.
    - Specialized non-monitoring graders return their own samples from ``base_golden``.
    - Any other grader falls back to the trajectory subset of ``base_golden``.
    """
    # Lazy import avoids the engine.scorers <-> engine.graders import cycle.
    from engine.graders.registry import get_canonical_grader

    canonical = get_canonical_grader(grader_name)
    resolved = canonical.name if canonical else grader_name
    if resolved in PER_GRADER_CALIBRATION_DATASETS:
        return list(PER_GRADER_CALIBRATION_DATASETS[resolved])
    base = list(base_golden or [])
    if resolved in SPECIALIZED_GRADERS:
        return [s for s in base if s.failure_mode == resolved]
    return [s for s in base if s.failure_mode not in SPECIALIZED_GRADERS]
